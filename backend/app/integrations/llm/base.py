from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from typing import Any


@dataclass
class LLMToolCall:
    """
    Normalized tool call requested by an LLM.
    """

    id: str
    name: str
    arguments: dict[str, Any] = field(default_factory=dict)


@dataclass
class LLMUsage:
    """
    Normalized token usage returned by an LLM provider.

    input_tokens:
        Tokens sent to the provider.

    output_tokens:
        Tokens generated by the provider.

    total_tokens:
        Total input + output tokens.

    Values may be None when the provider does not expose
    usage information.
    """

    input_tokens: int | None = None
    output_tokens: int | None = None
    total_tokens: int | None = None

    @property
    def has_usage(self) -> bool:
        """
        Return True when at least one usage value is available.
        """

        return (
            self.input_tokens is not None
            or self.output_tokens is not None
            or self.total_tokens is not None
        )


@dataclass
class LLMResponse:
    """
    Normalized response returned by every LLM provider.
    """

    content: str
    provider: str
    model: str

    tool_calls: list[LLMToolCall] = field(
        default_factory=list
    )

    # ==========================================================
    # USAGE
    # ==========================================================

    usage: LLMUsage = field(
        default_factory=LLMUsage
    )

    # ==========================================================
    # RAW RESPONSE
    # ==========================================================

    raw_response: Any | None = None


class LLMProvider(ABC):
    """
    Common interface for all Trav Planner LLM providers.

    Implementations:
        - GeminiProvider
        - GroqProvider
        - ClaudeProvider
        - OllamaProvider
    """

    @property
    @abstractmethod
    def provider_name(self) -> str:
        """Return the provider identifier."""
        raise NotImplementedError

    @property
    @abstractmethod
    def model_name(self) -> str:
        """Return the configured model identifier."""
        raise NotImplementedError

    @abstractmethod
    async def generate(
        self,
        prompt: str,
        *,
        system_prompt: str | None = None,
        temperature: float = 0.2,
        max_output_tokens: int = 4096,
        **kwargs: Any,
    ) -> LLMResponse:
        """
        Generate a normal text response from the LLM.
        """
        raise NotImplementedError

    async def generate_with_tools(
        self,
        prompt: str,
        *,
        tools: list[dict[str, Any]],
        system_prompt: str | None = None,
        temperature: float = 0.2,
        max_output_tokens: int = 4096,
        **kwargs: Any,
    ) -> LLMResponse:
        """
        Generate a response with tool/function calling.

        Providers that support native tool calling should override
        this method.
        """

        raise NotImplementedError(
            f"Tool calling is not implemented for "
            f"provider '{self.provider_name}'."
        )

    async def continue_with_tool_results(
        self,
        *,
        response: LLMResponse,
        tool_results: list[dict[str, Any]],
        tools: list[dict[str, Any]],
        system_prompt: str | None = None,
        temperature: float = 0.2,
        max_output_tokens: int = 4096,
        **kwargs: Any,
    ) -> LLMResponse:
        """
        Continue an LLM conversation after tool execution.

        The provider receives the previous LLM response containing
        the tool call and the results produced by the tool executor.
        """

        raise NotImplementedError(
            f"Tool-result continuation is not implemented for "
            f"provider '{self.provider_name}'."
        )