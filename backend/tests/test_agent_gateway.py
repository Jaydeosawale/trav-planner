# ==========================================================
# BILLING DATABASE HELPERS
# ==========================================================


async def enable_soft_billing_in_database() -> None:
    """
    Enable SOFT paid billing through the real
    AdminBillingService and PostgreSQL.

    The production gateway loads billing configuration
    from PostgreSQL before handling an AI request.
    """

    service = AdminBillingService(
        billing_policy=BillingPolicy(),
        paid_provider="groq",
    )

    async with SessionLocal() as db:

        await service.load_from_database(
            db
        )

        await service.soft_enable(
            db,
            paid_provider="groq",
            daily_budget=10.0,
            monthly_budget=100.0,
            admin_id=ADMIN_ID,
        )


async def disable_billing_in_database() -> None:
    """
    Disable paid billing through PostgreSQL.

    Leaves the database in the safe:

        paid_enabled = False
        mode = free_only

    state.
    """

    service = AdminBillingService(
        billing_policy=BillingPolicy(),
        paid_provider="groq",
    )

    async with SessionLocal() as db:

        await service.load_from_database(
            db
        )

        await service.disable(
            db,
            admin_id=ADMIN_ID,
        )


# ==========================================================
# ASSERTION HELPERS
# ==========================================================


def assert_free_response(
    response,
    *,
    provider: str,
) -> None:

    assert response.success is True, (
        "Expected successful response, "
        f"got success={response.success}"
    )

    assert response.metadata is not None

    assert response.metadata["provider"] == provider, (
        "Expected provider "
        f"{provider}, got "
        f"{response.metadata.get('provider')}"
    )

    assert response.metadata["mode"] == "free", (
        "Expected FREE mode, got "
        f"{response.metadata.get('mode')}"
    )


def assert_blocked_response(
    response,
) -> None:

    assert response.success is False, (
        "Expected blocked response, "
        f"got success={response.success}"
    )

    assert response.metadata is not None

    assert response.metadata["mode"] == "blocked", (
        "Expected BLOCKED mode, got "
        f"{response.metadata.get('mode')}"
    )

    assert response.metadata["provider"] is None, (
        "Blocked response must not select a provider."
    )

    assert (
        response.metadata["billing_enabled"]
        is False
    ), (
        "Paid billing should be disabled."
    )


def assert_paid_response(
    response,
) -> None:

    assert response.success is True, (
        "Expected successful paid response, "
        f"got success={response.success}"
    )

    assert response.metadata is not None

    assert response.metadata["provider"] == "groq", (
        "Expected paid provider groq, got "
        f"{response.metadata.get('provider')}"
    )

    assert response.metadata["mode"] == "paid", (
        "Expected PAID mode, got "
        f"{response.metadata.get('mode')}"
    )


