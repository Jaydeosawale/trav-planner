async def main() -> None:

    from app.agents.travel_planner import (
        TravelPlanningAgent,
    )

    from app.integrations.llm.gateway import (
        AIGateway,
    )

    print()
    print("=" * 60)
    print("TRAVEL PLANNER AGENT → AI GATEWAY TEST")
    print("=" * 60)

    # ======================================================
    # CREATE TEST QUOTA MANAGER
    # ======================================================

    quota_manager = TestQuotaManager()

    # ======================================================
    # CREATE REAL PRODUCTION GATEWAY
    # ======================================================

    gateway = AIGateway(
        quota_manager=quota_manager,
        billing_policy=BillingPolicy(),
        free_providers=FREE_PROVIDERS,
        paid_provider="groq",
    )

    # ======================================================
    # TEST-ONLY PROVIDER OVERRIDE
    # ======================================================
    #
    # IMPORTANT:
    #
    # ProviderManager still decides:
    #
    #     groq
    #     gemini
    #     blocked
    #     paid groq
    #
    # We only prevent the Gateway from constructing
    # the real Groq/Gemini clients.
    #
    # Therefore this test does NOT require:
    #
    #     GROQ_API_KEY
    #     GEMINI_API_KEY
    #
    # and does NOT consume external API quota.
    #

    def test_create_provider(
        provider_name: str,
    ):
        return MockLLMProvider(
            provider_name
        )

    gateway._create_provider = (
        test_create_provider
    )

    # ======================================================
    # CREATE AGENT
    # ======================================================

    agent = TravelPlanningAgent(
        gateway=gateway,
    )

    # ======================================================
    # CASE 1
    # GROQ FREE AVAILABLE
    # ======================================================

    print_case(
        "CASE 1 — AGENT → GROQ FREE"
    )

    # Safe billing state.
    await disable_billing_in_database()

    # Both providers available.
    # Provider order is:
    #
    #     groq
    #     gemini
    #
    # Therefore Groq must be selected.
    quota_manager.reset_all()

    response = await agent.run(
        "Plan a trip to Mumbai for 3 days."
    )

    print("Success :", response.success)
    print("Agent   :", response.agent)
    print("Content :", response.content)
    print("Metadata:", response.metadata)

    assert_free_response(
        response,
        provider="groq",
    )

    print("PASSED")

    # ======================================================
    # CASE 2
    # GROQ EXHAUSTED → GEMINI FREE
    # ======================================================

    print_case(
        "CASE 2 — GROQ EXHAUSTED → GEMINI FREE"
    )

    # Billing remains disabled.
    await disable_billing_in_database()

    # Groq exhausted.
    quota_manager.set_exhausted(
        "groq",
        reset_minutes=18,
    )

    # Gemini remains available.
    quota_manager.set_available(
        "gemini"
    )

    response = await agent.run(
        "Plan a trip to Delhi for 4 days."
    )

    print("Success :", response.success)
    print("Agent   :", response.agent)
    print("Content :", response.content)
    print("Metadata:", response.metadata)

    assert_free_response(
        response,
        provider="gemini",
    )

    print("PASSED")

    # ======================================================
    # CASE 3
    # ALL FREE EXHAUSTED + BILLING OFF
    # ======================================================

    print_case(
        "CASE 3 — ALL FREE EXHAUSTED + BILLING OFF"
    )

    # Paid AI must be disabled.
    await disable_billing_in_database()

    # Exhaust Groq + Gemini.
    quota_manager.exhaust_all()

    response = await agent.run(
        "Plan a trip to Goa for 5 days."
    )

    print("Success :", response.success)
    print("Agent   :", response.agent)
    print("Content :", response.content)
    print("Metadata:", response.metadata)

    assert_blocked_response(
        response
    )

    print("PASSED")

    # ======================================================
    # CASE 4
    # ALL FREE EXHAUSTED + SOFT BILLING ON
    # ======================================================

    print_case(
        "CASE 4 — ALL FREE EXHAUSTED + SOFT BILLING ON"
    )

    # Free providers stay exhausted.
    quota_manager.exhaust_all()

    # Enable paid AI through the real persistent
    # AdminBillingService.
    await enable_soft_billing_in_database()

    response = await agent.run(
        "Plan a trip to Jaipur for 4 days."
    )

    print("Success :", response.success)
    print("Agent   :", response.agent)
    print("Content :", response.content)
    print("Metadata:", response.metadata)

    assert_paid_response(
        response
    )

    print("PASSED")

    # ======================================================
    # CASE 5
    # DISABLE BILLING AGAIN
    # ======================================================

    print_case(
        "CASE 5 — DISABLE BILLING → BLOCK PAID FALLBACK"
    )

    # Disable paid AI again.
    await disable_billing_in_database()

    # Free providers remain exhausted.
    quota_manager.exhaust_all()

    response = await agent.run(
        "Plan a trip to Kerala for 5 days."
    )

    print("Success :", response.success)
    print("Agent   :", response.agent)
    print("Content :", response.content)
    print("Metadata:", response.metadata)

    assert_blocked_response(
        response
    )

    print("PASSED")

    # ======================================================
    # FINAL CLEANUP
    # ======================================================

    # Always leave the real database in the safe state.
    await disable_billing_in_database()

    # ======================================================
    # COMPLETE
    # ======================================================

    print()
    print("=" * 60)
    print("TRAVEL PLANNER AGENT GATEWAY TEST: PASSED")
    print("=" * 60)


# ==========================================================
# ENTRY POINT
# ==========================================================


if __name__ == "__main__":
    asyncio.run(main())