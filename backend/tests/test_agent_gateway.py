# ==========================================================
# TEST QUOTA OBJECT
# ==========================================================


@dataclass
class TestProviderQuota:
    """
    Test-only representation of a provider's free quota.

    ProviderManager only needs:

        - provider
        - minutes_until_reset()
    """

    provider: str
    available: bool = True
    reset_minutes: int = 18

    def minutes_until_reset(self) -> int:
        return self.reset_minutes


# ==========================================================
# TEST QUOTA MANAGER
# ==========================================================


class TestQuotaManager:
    """
    Test-only quota manager.

    Allows us to simulate:

        Groq available
        Groq exhausted
        Gemini available
        Gemini exhausted

    without touching real provider quotas.
    """

    def __init__(self) -> None:

        self.providers = {
            "groq": TestProviderQuota(
                provider="groq",
                available=True,
                reset_minutes=18,
            ),
            "gemini": TestProviderQuota(
                provider="gemini",
                available=True,
                reset_minutes=18,
            ),
        }

    # ------------------------------------------------------
    # Provider state
    # ------------------------------------------------------

    def set_available(
        self,
        provider: str,
    ) -> None:

        if provider not in self.providers:
            raise ValueError(
                f"Unknown provider: {provider}"
            )

        self.providers[provider].available = True

    def set_exhausted(
        self,
        provider: str,
        *,
        reset_minutes: int = 18,
    ) -> None:

        if provider not in self.providers:
            raise ValueError(
                f"Unknown provider: {provider}"
            )

        self.providers[provider].available = False

        self.providers[provider].reset_minutes = (
            reset_minutes
        )

    def reset_all(self) -> None:
        """
        Make all free providers available.
        """

        for provider in self.providers.values():
            provider.available = True
            provider.reset_minutes = 18

    def exhaust_all(self) -> None:
        """
        Exhaust all free providers.
        """

        for provider in self.providers.values():
            provider.available = False
            provider.reset_minutes = 18

    # ------------------------------------------------------
    # ProviderManager interface
    # ------------------------------------------------------

    def available_free(
        self,
        providers: list[str],
    ) -> list[TestProviderQuota]:
        """
        Return available free providers.

        ProviderManager selects the first provider,
        so preserve the configured order.
        """

        return [
            self.providers[provider]
            for provider in providers
            if (
                provider in self.providers
                and self.providers[provider].available
            )
        ]

    def nearest_reset(
        self,
        providers: list[str],
    ) -> TestProviderQuota | None:
        """
        Return the provider whose quota resets first.
        """

        exhausted = [
            self.providers[provider]
            for provider in providers
            if (
                provider in self.providers
                and not self.providers[provider].available
            )
        ]

        if not exhausted:
            return None

        return min(
            exhausted,
            key=lambda provider: (
                provider.reset_minutes
            ),
        )


